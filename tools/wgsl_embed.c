// wgsl_embed.c - the shaders (engine/gpu/shaders/*.wgsl) as C strings, so the engine carries
// them inside (no files to find at run time, natively or in a browser). Built and run by the
// Makefile:
//
//     wgsl_embed out.c a.wgsl b.wgsl ...
//
// writes out.c with `const char lr_wgsl_a[]`, `lr_wgsl_b[]`, ...: each file's text, line for
// line. A file using one declares it: extern const char lr_wgsl_a[];
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static int fail(const char *what, const char *name){
    fprintf(stderr, "wgsl_embed: %s: %s\n", what, name);
    return 1;
}

int main(int argc, char **argv){
    if (argc < 2){ fprintf(stderr, "usage: wgsl_embed out.c file.wgsl...\n"); return 1; }
    // written to a temporary name first: a failed run leaves no half file behind
    char tmp[1024];
    snprintf(tmp, sizeof(tmp), "%s.tmp", argv[1]);
    FILE *out = fopen(tmp, "wb");
    if (!out) return fail("cannot write", tmp);
    fprintf(out, "// generated by tools/wgsl_embed.c from engine/gpu/shaders: do not edit\n#ifdef LR_GPU\n");
    for (int i = 2; i < argc; i++){
        const char *path = argv[i], *base = strrchr(path, '/');
        base = base ? base + 1 : path;
        size_t n = strlen(base);
        if (n < 6 || strcmp(base + n - 5, ".wgsl")){ fclose(out); remove(tmp); return fail("not a .wgsl file", path); }
        for (size_t k = 0; k + 5 < n; k++){
            char c = base[k];
            if (!((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c == '_')){ fclose(out); remove(tmp); return fail("names are a-z, 0-9, _", path); }
        }
        FILE *in = fopen(path, "rb");
        if (!in){ fclose(out); remove(tmp); return fail("cannot read", path); }
        fprintf(out, "\nconst char lr_wgsl_%.*s[] =\n    \"", (int)(n - 5), base);
        int c, col = 0, any = 0;
        while ((c = fgetc(in)) != EOF){
            any = 1;
            if (c == '\r') continue;
            if (c == '\n'){ fputs("\\n\"\n    \"", out); col = 0; continue; }
            if (c == '\\' || c == '"' || c == '?') fputc('\\', out);      // ('?': no trigraphs)
            if (c == '\t') fputs("\\t", out);
            else if (c < 32 || c > 126) fprintf(out, "\\%03o", c);
            else fputc(c, out);
            col++;
        }
        (void)any; (void)col;
        fputs("\";\n", out);
        fclose(in);
    }
    fprintf(out, "\n#else\ntypedef int lr_wgsl_unused;   // (no GPU: no shaders)\n#endif\n");
    if (fclose(out)){ remove(tmp); return fail("cannot write", tmp); }
    remove(argv[1]);
    if (rename(tmp, argv[1])) return fail("cannot rename to", argv[1]);
    return 0;
}
